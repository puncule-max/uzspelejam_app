export type Dictionary = typeof dictionaries.lv;

export async function getLocale(): Promise<Locale> {
  const cookieStore = await cookies();
  const saved = cookieStore.get("uz_locale")?.value;
  if (saved === "lv" || saved === "en") return saved;
  const acceptLanguage = (await headers()).get("accept-language")?.toLowerCase() ?? "";
  return acceptLanguage.startsWith("lv") ? "lv" : "en";
}

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale] as Dictionary;
}

export function interpolate(text: string, values: Record<string,string|number>) {
  return Object.entries(values).reduce((result,[key,value]) => result.replaceAll(`{${key}}`, String(value)), text);
}
